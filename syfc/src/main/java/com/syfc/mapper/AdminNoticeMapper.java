package com.syfc.mapper;

import java.sql.SQLException;
import java.util.List;
import java.util.Map;

import com.syfc.dto.AdminNoticeDTO;

/*
 * =========================================================
 * 관리자 - 공지사항 Mapper
 * =========================================================
 *
 * adminNoticeMapper.xml의 SQL과 연결되는 인터페이스
 *
 * ★ board.b_Type
 * 0 : 자유게시판
 * 1 : 공지사항
 *
 * ★ 공지사항은 상단고정 기능을 사용하지 않으므로
 * listNoticeTop() 메서드는 제거한다.
 */
public interface AdminNoticeMapper {

	// =========================================================
	// 공지사항 등록
	// =========================================================
	public void insertNotice(AdminNoticeDTO dto) throws SQLException;


	// =========================================================
	// 공지사항 전체 개수
	// 검색조건에 맞는 공지사항 개수를 가져온다.
	// =========================================================
	public int dataCount(Map<String, Object> map);


	// =========================================================
	// 공지사항 목록
	// 페이징과 검색조건을 적용한 목록을 가져온다.
	// =========================================================
	public List<AdminNoticeDTO> listNotice(Map<String, Object> map);


	// =========================================================
	// 공지사항 상세조회
	// 게시글 번호로 공지사항 한 건을 가져온다.
	// =========================================================
	public AdminNoticeDTO findById(long bNum);


	// =========================================================
	// 이전 공지사항
	// 현재 글보다 이전에 위치한 공지사항을 가져온다.
	// =========================================================
	public AdminNoticeDTO findByPrev(Map<String, Object> map);


	// =========================================================
	// 다음 공지사항
	// 현재 글보다 다음에 위치한 공지사항을 가져온다.
	// =========================================================
	public AdminNoticeDTO findByNext(Map<String, Object> map);


	// =========================================================
	// 조회수 증가
	// =========================================================
	public void updateHitCount(long bNum) throws SQLException;


	// =========================================================
	// 공지사항 수정
	// =========================================================
	public void updateNotice(AdminNoticeDTO dto) throws SQLException;


	// =========================================================
	// 공지사항 삭제
	//
	// ★ 공지사항은 블라인드가 아니라 실제 DELETE
	// =========================================================
	public void deleteNotice(long bNum) throws SQLException;
}